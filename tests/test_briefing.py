"""The write-up: one file holding everything known about a concept.

What matters is provenance. A quote from the call has to read as a quote, model
prose has to read as unverified, and a concept developed from the private
archive has to say so before anything else.
"""

import pytest

from grant_recommender import briefing

CALL = {
	'topic_code': 'OPEN-1',
	'title': 'Long-term CGM for type 2 diabetes',
	'deadlines': ['2099-01-01T17:00:00'],
	'source_url': 'https://example.org/open-1',
}
ITEM = {
	'job_id': 'job1',
	'model': 'gemma4:12b-mlx',
	'trial': True,
	'archive': False,
	'concept': {
		'concept_id': '1',
		'title': 'Forecasting glucose',
		'problem': 'Glucose forecasting is unreliable.',
		'central_hypothesis': 'Meal logs help.',
		'objectives': ['Build a forecaster', 'Validate it'],
		'principal_feasibility_risk': 'Data access.',
		'call_evidence': [{'source_id': 'CALL_TEXT', 'claim_supported': 'the call asks for this'}],
		'researcher_evidence': [],
	},
}
ASSESSMENT = {'state': 'uncertain', 'reason': 'Check the consortium rules.'}
FIT = {'keyword_overlap': 0.25, 'rank': 1}
REFINED = {
	'model': 'gemma4:12b-mlx',
	'fields': {'budget': {'value': '2 million euro', 'quote': 'a budget of 2 million euro'}},
	'synopsis': 'The call funds forecasting work.',
}
ROUND = {
	'consolidated': {
		'outcome': 'revise',
		'tally': {'fund': 0, 'revise': 2, 'reject': 1},
		'unsupported_claims': [
			{'raised_by': 'methods', 'claim': 'it is novel', 'why_unsupported': 'no citation'}
		],
		'questions': [],
	},
	'reviews': {
		'methods': {
			'label': 'Methodology & evaluation',
			'status': 'succeeded',
			'result': {
				'verdict': 'revise',
				'verdict_reason': 'needs a sample size',
				'strengths': ['clear aim'],
				'weaknesses': ['no power analysis'],
				'questions_for_applicant': ['How many subjects?'],
			},
		}
	},
}
DRAFT = {
	'id': 'draft1',
	'notice': 'Working draft, not an official template.',
	'sections': {
		'aims': {'text': 'The aim is to forecast.', 'missing_info': ['Confirm the question.']},
		'methods': {'text': '', 'missing_info': ['Specify the design.']},
	},
}


def compose(**overrides):
	kwargs = {
		'call': CALL,
		'item': ITEM,
		'fit': FIT,
		'assessment': ASSESSMENT,
		'refined': REFINED,
		'round_': ROUND,
		'draft': DRAFT,
		'files': [],
		'source': 'EU Funding Portal',
	}
	return briefing.compose(**{**kwargs, **overrides})


def test_it_carries_the_call_the_concept_the_panel_and_the_open_questions():
	text = compose()

	assert '# Forecasting glucose' in text
	assert 'Long-term CGM for type 2 diabetes' in text
	assert '2099-01-01' in text
	assert 'uncertain — Check the consortium rules.' in text
	assert 'Glucose forecasting is unreliable.' in text
	assert 'Outcome: REVISE' in text
	assert 'no power analysis' in text
	assert '- [ ] Specify the design.' in text


def test_a_quote_from_the_call_is_marked_as_quoted_not_as_fact():
	text = compose()

	assert '**budget**: 2 million euro' in text
	assert '> a budget of 2 million euro' in text


def test_model_prose_says_which_model_wrote_it_and_that_it_is_unchecked():
	text = compose()

	assert 'Generated by gemma4:12b-mlx in run `job1`' in text
	assert 'Unverified.' in text
	assert 'exploratory trial with eligibility unconfirmed' in text
	assert 'nothing generated by a model has been checked by a person' in text


def test_a_concept_from_the_private_archive_says_so_before_anything_else():
	"""Its wording may echo an archived, third-party-authored application."""
	text = compose(item={**ITEM, 'archive': True})

	warning = text.index('private proposal archive')
	assert warning < text.index('## The call')
	assert 'Do not circulate this file' in text


def test_an_unreviewed_undrafted_concept_says_what_is_missing_rather_than_nothing():
	text = compose(round_=None, draft=None)

	assert 'No review round has been run' in text
	assert 'Press p in the panel to open one.' in text


def test_downloaded_files_are_listed():
	from pathlib import Path

	text = compose(files=[Path('/tmp/x/Antragsvorlage.pdf')])

	assert '- `Antragsvorlage.pdf`' in text


def test_the_filename_is_safe_and_names_the_run_and_the_concept(tmp_path, monkeypatch):
	monkeypatch.setattr(briefing, 'ROOT', tmp_path / 'briefings')
	odd_call = {**CALL, 'topic_code': 'DFG/../weird code'}

	path = briefing.write(compose(), odd_call, ITEM)

	assert path.name.startswith('DFG-weird-code-job1-1-')
	assert path.name.endswith('.md')
	# Whatever the topic code contains, the result is one name inside ROOT.
	assert path.parent == tmp_path / 'briefings'
	assert path.resolve().parent == (tmp_path / 'briefings').resolve()


def test_an_ordinary_key_keeps_its_plain_name():
	assert briefing.path_for(CALL, ITEM).name == 'OPEN-1-job1-1.md'


def test_two_concepts_that_sanitise_alike_do_not_share_a_filename():
	"""A concept id is a model-produced string, so two of them can reduce to the
	same stem and one briefing would silently replace the other."""
	first = {**ITEM, 'concept': {**ITEM['concept'], 'concept_id': '1 (main)'}}
	second = {**ITEM, 'concept': {**ITEM['concept'], 'concept_id': '1  main'}}

	assert briefing.path_for(CALL, first) != briefing.path_for(CALL, second)


def test_a_rewrite_never_replaces_an_edited_briefing(tmp_path, monkeypatch):
	"""The whole point of the file is that the researcher writes in it."""
	monkeypatch.setattr(briefing, 'ROOT', tmp_path / 'briefings')
	text = compose()
	first = briefing.write(text, CALL, ITEM)

	# Writing the same content again is not a new file.
	assert briefing.write(text, CALL, ITEM) == first

	first.write_text(text + '\n\nMy own notes, written by hand.')
	second = briefing.write(text, CALL, ITEM)

	assert second != first
	assert 'My own notes' in first.read_text()
	assert 'My own notes' not in second.read_text()
	assert second.read_text().startswith('# Forecasting glucose')


MINIMAL = {
	'call': {'topic_code': 'X'},
	'item': {'job_id': 'j', 'concept': {'concept_id': '1'}},
	'fit': {},
	'assessment': {'state': 'uncertain', 'reason': 'r'},
	'refined': None,
	'round_': None,
	'draft': None,
	'files': [],
	'source': 'S',
}


@pytest.mark.parametrize(
	('name', 'override'),
	[
		('nothing but the ids', {}),
		('no title on the call', {'call': {'topic_code': 'X', 'title': None}}),
		('a concept with no fields', {'item': {'job_id': 'j', 'concept': {'concept_id': '1'}}}),
		(
			'a round where a reviewer failed',
			{
				'round_': {
					'consolidated': {
						'outcome': None,
						'tally': {'fund': 0, 'revise': 0, 'reject': 0},
						'unsupported_claims': [],
						'questions': [],
					},
					'reviews': {'methods': {'status': 'failed', 'error': 'ollama down'}},
				}
			},
		),
		(
			'a round with no reviews block',
			{
				'round_': {
					'consolidated': {
						'outcome': 'fund',
						'tally': {'fund': 1, 'revise': 0, 'reject': 0},
						'unsupported_claims': [],
						'questions': [],
					}
				}
			},
		),
		('a draft with no sections', {'draft': {'id': 'd', 'notice': 'n', 'sections': {}}}),
		('a refinement that found nothing', {'refined': {'fields': {}, 'synopsis': ''}}),
		('a fit with no overlap', {'fit': {'rank': 3}}),
		('deadlines set to None', {'call': {'topic_code': 'X', 'deadlines': None}}),
	],
)
def test_it_writes_something_readable_whatever_the_stores_are_missing(name, override):
	"""It reads five stores written by different processes, any of which can be
	half-filled. A write-up that raises loses the researcher their notes."""
	text = briefing.compose(**{**MINIMAL, **override})

	assert text.startswith('#')
	assert '## The call' in text
	assert '## Review panel' in text
