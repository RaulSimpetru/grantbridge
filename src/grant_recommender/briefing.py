"""One Markdown file holding everything known about a concept.

The point of the tool is to leave the researcher with something they can open
and start writing from. Until this existed the work stopped at a decision: the
call, the facts quoted out of it, the concept, the panel's criticisms and the
draft's open questions each lived in a different store, and none of them in a
file anyone could take to a word processor.

Every line says where it came from. A quote from the call is marked as quoted,
anything a model wrote is marked as unverified, and a run seeded from the
private proposal archive says so at the top, because that text may echo an
archived, possibly third-party-authored application and must not leave this
machine.
"""

import hashlib
import re
from datetime import UTC, datetime
from pathlib import Path

from grant_recommender import refinement
from grant_recommender.lifecycle import CONCEPT_FIELDS

ROOT = Path(__file__).resolve().parents[2] / 'data/private/briefings'
# No dots: the extension is added here, and a topic code carrying '..' would
# otherwise survive into the filename. Separators are already excluded, so
# the result is always one name inside ROOT.
SAFE = re.compile(r'[^A-Za-z0-9_-]+')

ARCHIVE_WARNING = (
	'> **This concept was developed from the private proposal archive.** Its wording may '
	'echo an archived, possibly third-party-authored application. Do not circulate this '
	'file, and rewrite every passage before it goes anywhere.\n'
)

HEADER_NOTE = (
	'> Working notes assembled by GrantBridge. Nothing here is an application, and nothing '
	'generated by a model has been checked by a person. Confirm the call text, the deadline '
	'and the eligibility rules at the source before relying on any of it.\n'
)


def _bullets(values) -> str:
	if isinstance(values, list):
		return '\n'.join(f'- {item}' for item in values)
	return str(values)


def _call_section(call, fit, assessment, refined) -> list[str]:
	out = ['## The call', '']
	deadlines = call.get('deadlines') or []
	out.append(f'- **Deadline**: {", ".join(str(d)[:10] for d in deadlines) or "none recorded"}')
	basis = {
		'researcher_review': f'your own review of {assessment.get("source") or "the call"}'
		+ (f', {assessment["reviewed_at"][:10]}' if assessment.get('reviewed_at') else ''),
		'missing_review': 'nobody has reviewed this yet',
		'deadline': 'the recorded deadlines only',
	}.get(assessment.get('basis'), assessment.get('basis') or 'unrecorded basis')
	out.append(f'- **Eligibility**: {assessment["state"]} — {assessment["reason"]} ({basis})')
	overlap = fit.get('keyword_overlap')
	if overlap is not None:
		out.append(f'- **Portfolio overlap**: {overlap:.0%} (rank {fit.get("rank", "unranked")})')
	out.append(f'- **Source**: {call.get("source_url") or "not recorded"}')
	if call.get('source_warning'):
		out.append(f'- **Warning**: {call["source_warning"]}')
	out.append('')
	if not refined:
		out += [
			(
				'_The call text has not been read yet, so nothing below is quoted from it. '
				'Press e in the panel._'
			),
			'',
		]
	if refined and refined.get('fields'):
		out += ['### Quoted from the call text', '']
		for name, field in refined['fields'].items():
			out.append(f'**{name}**: {field["value"]}')
			# Every line prefixed: a quote containing a blank line otherwise
			# escapes the blockquote and reads as the briefing's own prose.
			out += [f'> {line}' for line in str(field['quote']).splitlines()]
			out.append('')
	if refined and refined.get('dropped'):
		out += [
			(
				'_These fields were extracted but their quote did not match the page, so they '
				f'were dropped: {", ".join(refined["dropped"])}._'
			),
			'',
		]
	if refined and refined.get('synopsis'):
		out += [
			'### Synopsis',
			'',
			refined['synopsis'],
			'',
			(
				f'_Written by {refined.get("model") or "a model"} from the call text. '
				f'Figures of {refinement.MIN_FIGURE_CHARS} or more characters were checked '
				'against that text; shorter numbers and the wording were not._'
			),
			'',
		]
	return out


def _concept_section(item) -> list[str]:
	concept = item['concept']
	out = ['## The concept', '']
	out.append(
		f'_Generated by {item.get("model") or "a model"} in run `{item["job_id"]}`'
		+ (', as an exploratory trial with eligibility unconfirmed' if item.get('trial') else '')
		+ '. Unverified._'
	)
	out.append('')
	for label, key in CONCEPT_FIELDS:
		value = concept.get(key)
		if value:
			out += [f'### {label.title()}', '', _bullets(value), '']
	call_evidence = concept.get('call_evidence') or []
	researcher_evidence = concept.get('researcher_evidence') or []
	if call_evidence or researcher_evidence:
		out += ['### Evidence it cites', '']
		archived = []
		for entry in call_evidence + researcher_evidence:
			source_id = str(entry.get('source_id', '?'))
			if source_id.upper().startswith('ARCHIVE'):
				archived.append(source_id)
				continue
			out.append(f'- `{source_id}` {entry.get("claim_supported", "")}')
		out.append('')
		if archived:
			# Named but not reproduced: the count and the location are what a
			# reader needs, and the claim text belongs to an archived application.
			out += ['**From the private archive**', '']
			out += [
				f'- `{source_id}` — an archived proposal, text withheld' for source_id in archived
			]
			out.append('')
	return out


def _review_section(round_) -> list[str]:
	if not round_:
		return ['## Review panel', '', '_No review round has been run on this concept._', '']
	summary = round_['consolidated']
	tally = summary['tally']
	records = round_.get('reviews') or {}
	model = next((r.get('model') for r in records.values() if r.get('model')), 'a local model')
	failed = [role for role, r in records.items() if r.get('status') != 'succeeded']
	out = [
		'## Review panel',
		'',
		(
			f'**Outcome: {(summary["outcome"] or "no verdict").upper()}** '
			f'(fund {tally["fund"]}, revise {tally["revise"]}, reject {tally["reject"]})'
		),
		'',
		(
			f"_{len(records)} rubric roles run by {model}. A rehearsal, not a funder's "
			'panel, and unverified._'
		),
		'',
	]
	if failed:
		out += [
			(
				f'_{len(failed)} of {len(records)} reviewers failed '
				f'({", ".join(sorted(failed))}), so this is a partial panel._'
			),
			'',
		]
	for role, record in (round_.get('reviews') or {}).items():
		if record.get('status') != 'succeeded':
			continue
		result = record['result']
		out += [
			f'### {record.get("label") or role}',
			'',
			f'_{result["verdict"].upper()}_ — {result["verdict_reason"]}',
			'',
		]
		for heading, key in (
			('Strengths', 'strengths'),
			('Weaknesses', 'weaknesses'),
			('Questions', 'questions_for_applicant'),
		):
			items = result.get(key) or []
			if items:
				out += [f'**{heading}**', '', _bullets(items), '']
	claims = summary.get('unsupported_claims') or []
	if claims:
		out += ['### Claims the panel could not find support for', '']
		out += [f'- ({c["raised_by"]}) {c["claim"]} — {c["why_unsupported"]}' for c in claims]
		out.append('')
	return out


def _draft_section(draft) -> list[str]:
	if not draft:
		return [
			'## Before you write',
			'',
			'_No draft has been opened for this concept. Press p in the panel to open one._',
			'',
		]
	out = ['## Before you write', '', f'_Draft `{draft["id"]}`. {draft["notice"]}_', '']
	for key, section in draft['sections'].items():
		origin = section.get('origin') or 'unknown origin'
		out.append(f'### {key.replace("_", " ").title()} — _{origin}_')
		out.append('')
		if section['text']:
			out += [section['text'], '']
		for question in section['missing_info']:
			out.append(f'- [ ] {question}')
		out.append('')
	return out


def compose(*, call, item, fit, assessment, refined, round_, draft, files, source) -> str:
	"""The whole briefing as Markdown. Pure: every store is read by the caller,
	including the source's display name, so nothing here imports a screen."""
	title = str(item['concept'].get('title') or 'Untitled concept')
	lines = [
		f'# {title}',
		'',
		f'**{call.get("title") or call["topic_code"]}**',
		'',
		f'{source} · `{call["topic_code"]}`',
		'',
	]
	if item.get('archive'):
		lines += [ARCHIVE_WARNING, '']
	lines += [HEADER_NOTE, '']
	lines += _call_section(call, fit, assessment, refined)
	lines += _concept_section(item)
	lines += _review_section(round_)
	lines += _draft_section(draft)
	if files:
		lines += ['## Files downloaded from the call page', '']
		lines += [f'- `{path.name}`' for path in files]
		lines.append('')
	return '\n'.join(lines).rstrip() + '\n'


def path_for(call: dict, item: dict) -> Path:
	raw = f'{call["topic_code"]}-{item["job_id"]}-{item["concept"]["concept_id"]}'
	stem = SAFE.sub('-', raw).strip('-')
	# A concept id is a model-produced string, so two of them can sanitise to
	# the same stem and one briefing would silently replace the other.
	if stem != raw:
		stem = f'{stem}-{hashlib.sha256(raw.encode()).hexdigest()[:6]}'
	return ROOT / f'{stem}.md'


def write(text: str, call: dict, item: dict) -> Path:
	"""Write the briefing, never over an edited one.

	The whole point of the file is that the researcher opens it and writes in
	it. Pressing w again a week later would otherwise replace their work with
	a fresh render of the same stores, so a file that no longer matches what
	this run composed gets a dated sibling instead.
	"""
	target = path_for(call, item)
	target.parent.mkdir(parents=True, exist_ok=True)
	if target.exists() and target.read_text() != text:
		stamp = datetime.now(UTC).strftime('%Y%m%d-%H%M%S')
		target = target.with_name(f'{target.stem}-{stamp}.md')
	target.write_text(text)
	return target
